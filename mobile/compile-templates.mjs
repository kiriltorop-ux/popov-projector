import { readFile, writeFile } from 'node:fs/promises';
import { compile } from '@vue/compiler-dom';

const docs = new URL('./docs/', import.meta.url);
const modules = ['views.mjs', 'studio.mjs', 'conversation.mjs', 'station.mjs'];
const output = ['// Generated by compile-templates.mjs. Edit the source templates.',
  "import * as Vue from './vendor/vue.esm-browser.prod.mjs';"];
function append(name, template) {
  const { code } = compile(template, { mode: 'function', prefixIdentifiers: true, hoistStatic: true });
  output.push(`export const ${name} = (Vue => {\n${code}\n})(Vue);`);
}

for (const file of modules) {
  const source = await readFile(new URL(file, docs), 'utf8');
  const components = source.split(/^(?:export )?const (\w+) = \{/m);
  for (let i = 1; i < components.length; i += 2) {
    const [, block] = components.slice(i, i + 2);
    if (!/^ {2}template:/m.test(block)) continue;
    const literal = block.match(/^ {2}template: (`[^\`]*`|'[^'\n]*'),/m)?.[1];
    if (!literal || literal.includes('${') || literal.includes('\\')) {
      throw new Error(`Expected a static template literal in ${file} (${components[i]}).`);
    }
    const name = components[i];
    append(name[0].toLowerCase() + name.slice(1) + 'Render', literal.slice(1, -1));
  }
}

const standalone = await readFile(new URL('popov.html', docs), 'utf8');
const content = standalone.match(/<div id="popov-root" v-cloak>([\s\S]*?)<\/div><\/body>/)?.[1];
if (!content) throw new Error('Cannot find the legacy visitor template.');
append('legacyPopovRender', content);
await writeFile(new URL('vue-renders.mjs', docs), output.join('\n\n') + '\n');
